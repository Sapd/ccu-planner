// German nouns for the counts line of the filters ("197 Upgrades", "23 von 197 angezeigt").
const NOUNS = { upgrades: ['Upgrade', 'Upgrades'], pledges: ['Pledge', 'Pledges'], ships: ['Schiff', 'Schiffe'], items: ['Artikel', 'Artikel'] };

/** Builder key (loc() in a view module) -> German twin with the same arguments. */
export const builders = {
  'filters.resultsText': (shown, total, noun) => {
    const [one, many] = NOUNS[noun] ?? [noun, noun];
    return shown === total ? `${total} ${total === 1 ? one : many}` : `${shown} von ${total} angezeigt`;
  },
  'filters.notLabel': (label) => `Nicht: ${t(label)}`,
  'storeBrowser.catalogAge': (fetchedAt, signedIn, now = new Date(), source = 'own') => {
    const w = whenText(fetchedAt, now);
    if (w && source === 'feed') return `Katalog aus dem CCU-Planner-Feed, ${w}`;
    return w ? (signedIn ? `Store-Katalog von ${w} · angemeldet` : `Öffentlicher Store-Katalog von ${w}`) : 'Noch kein Store-Katalog';
  },
};
